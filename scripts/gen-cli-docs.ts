// Regenerates the command reference in docs/cli.md from the CLI registry.
//   node scripts/gen-cli-docs.ts          rewrite docs/cli.md
//   node scripts/gen-cli-docs.ts --check  exit 1 if docs/cli.md is out of date
// Everything above the marker line is hand-written and kept as is.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COMMANDS, EXIT_CODES, GLOBAL_FLAGS, GROUPS, flagsOf, type CommandSpec, type FlagSpec } from "../src/cli/registry.ts";
import "../src/cli/commands/index.ts";
import { argsLabel, flagLabel } from "../src/cli/help.ts";

export const MARKER = "<!-- Everything below is generated by scripts/gen-cli-docs.ts from the command registry. Edit src/cli/commands/*.ts, not this. -->";
export const DOC_PATH = fileURLToPath(new URL("../docs/cli.md", import.meta.url));

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const anchor = (name: string) => name.replace(/\s+/g, "-");

function flagRow(f: FlagSpec): string {
  const extra = [
    f.default !== undefined && f.default !== false ? `Default \`${JSON.stringify(f.default)}\`.` : "",
    f.alias?.length ? `Also ${f.alias.map((a) => `\`--${a}\``).join(", ")}.` : "",
  ].filter(Boolean);
  return `| \`${cell(flagLabel(f))}\` | ${f.type} | ${cell([f.description, ...extra].join(" "))} |`;
}

function commandSection(c: CommandSpec): string {
  const out = [`### etude ${c.name}`, "", `<a id="${anchor(c.name)}"></a>`, "", c.summary];
  if (c.description) out.push("", c.description.trim());
  out.push("", "```", `etude ${c.name}${c.args?.length ? " " + argsLabel(c) : ""}${flagsOf(c).length ? " [flags]" : ""}`, "```");
  const traits = [c.writes ? "writes" : "read-only", c.dryRun ? "`--dry-run`" : null, c.confirm ? "needs `--yes`" : null, c.noDb ? "no database" : null].filter(Boolean);
  out.push("", `*${traits.join(" · ")}*`);
  if (c.args?.length) {
    out.push("", "| Argument | Description |", "| --- | --- |");
    for (const a of c.args) out.push(`| \`${a.name}${a.variadic ? "..." : ""}\`${a.required ? "" : " (optional)"} | ${cell(a.description)} |`);
  }
  const flags = flagsOf(c);
  if (flags.length) {
    out.push("", "| Flag | Type | Description |", "| --- | --- | --- |");
    for (const f of flags) out.push(flagRow(f));
  }
  if (c.dynamicFlags) out.push("", "Any other `--<field> VALUE` or `--<field>-file PATH` sets that field of the item (see `etude type show <type>` for field names).");
  if (c.output) out.push("", `Output: ${c.output}`);
  if (c.examples?.length) out.push("", "```sh", ...c.examples, "```");
  return out.join("\n");
}

export function generate(): string {
  const visible = COMMANDS.filter((c) => !c.legacy);
  const legacy = COMMANDS.filter((c) => c.legacy);
  const out: string[] = ["## Command reference", ""];
  out.push("### Global flags", "", "These work on every command, before or after the command words.", "", "| Flag | Type | Description |", "| --- | --- | --- |");
  for (const f of GLOBAL_FLAGS) out.push(flagRow(f));
  out.push("", "### Exit codes", "", "| Exit | `code` | Meaning |", "| --- | --- | --- |");
  for (const c of EXIT_CODES) out.push(`| ${c.exit} | \`${c.code}\` | ${cell(c.meaning)} |`);
  out.push("", "### Command tree", "");
  for (const g of GROUPS) {
    const cmds = visible.filter((c) => c.name.startsWith(g.name + " "));
    out.push(`- **${g.name}**: ${g.summary}${g.defaultVerb ? ` (\`etude ${g.name}\` alone runs \`${g.defaultVerb}\`)` : ""}`);
    for (const c of cmds) out.push(`  - [\`${c.name}\`](#${anchor(c.name)}) ${c.summary}`);
  }
  const top = visible.filter((c) => !c.name.includes(" "));
  out.push("- **top level**");
  for (const c of top) out.push(`  - [\`${c.name}\`](#${anchor(c.name)}) ${c.summary}`);

  for (const g of GROUPS) {
    out.push("", `## ${g.name}`, "", g.summary + ".");
    for (const c of visible.filter((x) => x.name.startsWith(g.name + " "))) out.push("", commandSection(c));
  }
  out.push("", "## Top-level commands");
  for (const c of top) out.push("", commandSection(c));
  if (legacy.length) {
    out.push("", "## Other spellings", "", "Kept so older scripts keep working. Each takes the same arguments and flags as its target.", "", "| Command | Same as |", "| --- | --- |");
    for (const c of legacy) out.push(`| \`etude ${c.name}\` | [\`etude ${c.aliasOf}\`](#${anchor(c.aliasOf!)}) |`);
  }
  return out.join("\n") + "\n";
}

export function render(current: string): string {
  const i = current.indexOf(MARKER);
  const head = i >= 0 ? current.slice(0, i) : current.trimEnd() + "\n\n";
  return head + MARKER + "\n\n" + generate();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const current = readFileSync(DOC_PATH, "utf8");
  const next = render(current);
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("docs/cli.md is out of date; run node scripts/gen-cli-docs.ts");
      process.exit(1);
    }
    console.log("docs/cli.md is up to date");
  } else {
    writeFileSync(DOC_PATH, next);
    console.log(`wrote ${DOC_PATH}`);
  }
}
